"""Pair the immutable control and 16x16 rows with Stage 22's official 8x8 rows.

Only reads CSVs generated by the unmodified organizer's submission generator.
The expanded official formula is calculated independently for every image.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
CONTROL = "control"
PREVIOUS = "black_occlusion16_signed"
CANDIDATE = "black_occlusion8_signed"
METRICS = ("Faithfulness", "Max_Sensitivity", "Sparsity")
TERMS = ("faithfulness_contribution", "sensitivity_contribution", "sparsity_contribution")
COLUMNS = ["Id", *METRICS]
CONTROL_SCORE = 75.58758067203142
PREVIOUS_SCORE = 76.05259533915773


def read_metrics(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path)
    if frame.columns.tolist() != COLUMNS or frame.Id.tolist() != list(range(1, 10)):
        raise ValueError(f"Invalid official nine-image CSV schema/order: {path}")
    if not np.isfinite(frame[list(METRICS)].to_numpy(dtype=float)).all():
        raise ValueError(f"Non-finite metric in {path}")
    return frame


def contributions(frame: pd.DataFrame) -> pd.DataFrame:
    parts = pd.DataFrame(index=frame.index)
    parts[TERMS[0]] = 20.0 * (1.0 + frame.Faithfulness)
    parts[TERMS[1]] = 30.0 * np.maximum(1.0 - frame.Max_Sensitivity / 2.0, 0.0)
    parts[TERMS[2]] = 30.0 * frame.Sparsity
    parts["row_score"] = parts[list(TERMS)].sum(axis=1)
    return parts


def describe(frame: pd.DataFrame) -> dict:
    parts = contributions(frame)
    return {
        "means": {metric: float(frame[metric].mean()) for metric in METRICS},
        "contributions": {term: float(parts[term].mean()) for term in TERMS},
        "score_from_rows": float(parts.row_score.mean()),
    }


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pending = path.with_name(path.name + ".pending")
    try:
        with pending.open("w", encoding="utf-8") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(pending, path)
    finally:
        pending.unlink(missing_ok=True)


def comparison_summary(name: str, baseline: str, frames: dict, parts: dict,
                       output: pd.DataFrame) -> dict:
    delta = parts[name].row_score - parts[baseline].row_score
    return {
        "metric_mean_deltas": {
            metric: float((frames[name][metric] - frames[baseline][metric]).mean())
            for metric in METRICS
        },
        "contribution_mean_deltas": {
            term: float((parts[name][term] - parts[baseline][term]).mean())
            for term in TERMS
        },
        "score_delta": float(delta.mean()),
        "median_row_score_delta": float(delta.median()),
        "images_improved": int((delta > 0).sum()),
        "images_declined": int((delta < 0).sum()),
        "improved_ids": [int(row) for row in frames[name].Id[delta > 0]],
        "id2_row_score_delta": float(delta.iloc[1]),
        "id2_share_of_nine_row_delta_sum": (
            float(delta.iloc[1] / delta.sum()) if abs(float(delta.sum())) > 1e-12 else None
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT)
    parser.add_argument("--control-root", type=Path, default=ROOT.parent / "output_mac_next")
    parser.add_argument("--stage21-root", type=Path, default=ROOT.parent / "output_mac_stage21")
    parser.add_argument("--official-csv", type=Path,
                        default=Path("/Users/xiefujun/Downloads/stage17/official/data/test.csv"))
    args = parser.parse_args()

    frames = {
        CONTROL: read_metrics(args.control_root / "runs/control.csv"),
        PREVIOUS: read_metrics(args.stage21_root / "runs" / f"{PREVIOUS}.csv"),
        CANDIDATE: read_metrics(args.output_dir / "runs" / f"{CANDIDATE}.csv"),
    }
    official = pd.read_csv(args.official_csv)
    if (official.columns.tolist() != ["image", "category"] or len(official) != 9
            or official.image.duplicated().any()):
        raise ValueError(f"Unexpected official test list: {args.official_csv}")
    output = pd.DataFrame({"Id": list(range(1, 10)), "image": official.image,
                           "category": official.category})
    parts = {name: contributions(frame) for name, frame in frames.items()}
    for name, frame in frames.items():
        for metric in METRICS:
            output[f"{name}_{metric}"] = frame[metric]
        for term in (*TERMS, "row_score"):
            output[f"{name}_{term}"] = parts[name][term]
    for name in (PREVIOUS, CANDIDATE):
        for baseline in (CONTROL, PREVIOUS):
            if name == baseline:
                continue
            for metric in METRICS:
                output[f"{name}_delta_{metric}_vs_{baseline}"] = (
                    frames[name][metric] - frames[baseline][metric]
                )
            for term in (*TERMS, "row_score"):
                output[f"{name}_delta_{term}_vs_{baseline}"] = (
                    parts[name][term] - parts[baseline][term]
                )
    summary = {name: describe(frame) for name, frame in frames.items()}
    score_paths = {
        CONTROL: args.control_root / "runs/control.score.json",
        PREVIOUS: args.stage21_root / "runs" / f"{PREVIOUS}.score.json",
        CANDIDATE: args.output_dir / "runs" / f"{CANDIDATE}.score.json",
    }
    for name, path in score_paths.items():
        official_score = float(json.loads(path.read_text(encoding="utf-8"))["official_score_0_to_100"])
        if abs(summary[name]["score_from_rows"] - official_score) > 1e-9:
            raise ValueError(f"Official and expanded-formula scores disagree for {name}")
        summary[name]["official_score"] = official_score
    if abs(summary[CONTROL]["score_from_rows"] - CONTROL_SCORE) > 1e-9:
        raise ValueError("Read-only Mac control score changed")
    if abs(summary[PREVIOUS]["score_from_rows"] - PREVIOUS_SCORE) > 1e-9:
        raise ValueError("Read-only Stage 21 score changed")
    summary[PREVIOUS]["vs_control"] = comparison_summary(
        PREVIOUS, CONTROL, frames, parts, output
    )
    summary[CANDIDATE]["vs_control"] = comparison_summary(
        CANDIDATE, CONTROL, frames, parts, output
    )
    summary[CANDIDATE]["vs_stage21"] = comparison_summary(
        CANDIDATE, PREVIOUS, frames, parts, output
    )
    summary[CANDIDATE]["strictly_above_stage21"] = (
        summary[CANDIDATE]["official_score"] > summary[PREVIOUS]["official_score"]
    )
    atomic_write(args.output_dir / "per_image_comparison.csv", output.to_csv(index=False))
    atomic_write(args.output_dir / "summary.json",
                 json.dumps(summary, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
